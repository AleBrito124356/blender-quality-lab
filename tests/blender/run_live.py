"""Run inside Blender on a saved .blend: run the live inspection code the way a harness does.

Blender MCP's execute_code runs `exec(code, {"bpy": bpy})` with stdout captured. Before that, this
script changes viewport-only state (hide in viewport, viewport modifiers) so it differs from render
visibility, which the inspector must mirror and then put back. It records the state before and
after, and runs the code a second time with separate globals and locals.

Usage: blender ... scene.blend --python run_live.py -- CODE.py OUTPUT.json
"""

import contextlib
import io
import json
import sys

import bpy

code_path, output = sys.argv[sys.argv.index("--") + 1 :][:2]
scene, view_layer = bpy.context.scene, bpy.context.view_layer


def snapshot():
    layers = {}

    def walk(layer):
        layers[layer.name] = [layer.hide_viewport, layer.exclude]
        for child in layer.children:
            walk(child)

    walk(view_layer.layer_collection)
    return {
        "frame": [scene.frame_current, scene.frame_subframe],
        "dirty": bpy.data.is_dirty,
        "collections": {c.name: c.hide_viewport for c in bpy.data.collections},
        "layer_collections": layers,
        "objects": {
            o.name: [
                o.hide_viewport,
                o.hide_get(view_layer=view_layer),
                getattr(o, "show_instancer_for_viewport", None),
                [m.show_viewport for m in o.modifiers],
                list(o.location),
            ]
            for o in scene.objects
        },
        "datablocks": {
            kind: sorted(block.name for block in getattr(bpy.data, kind))
            for kind in ("objects", "meshes", "materials", "collections", "scenes", "texts", "images")
        },
    }


meshes = [o for o in scene.objects if o.type == "MESH"]
if meshes:
    meshes[0].hide_set(True)
    meshes[-1].hide_viewport = True
    for obj in meshes:
        for modifier in obj.modifiers[:1]:
            modifier.show_viewport = False
for collection in bpy.data.collections:
    collection.hide_viewport = not collection.hide_render  # the opposite of what render shows

code = open(code_path, encoding="utf-8").read()
before = snapshot()
namespace = {"bpy": bpy}
captured = io.StringIO()
with contextlib.redirect_stdout(captured):
    exec(code, namespace)  # noqa: S102 - code generated by blender_quality.live in the test itself
after = snapshot()
split = io.StringIO()
with contextlib.redirect_stdout(split):
    exec(code, {"bpy": bpy}, {})  # noqa: S102 - same code, separate globals and locals
with open(output, "w", encoding="utf-8") as handle:
    json.dump(
        {
            "stdout": captured.getvalue(),
            "stdout_split_namespace": split.getvalue(),
            "namespace": sorted(k for k in namespace if k != "__builtins__"),
            "before": before,
            "after": after,
        },
        handle,
    )
